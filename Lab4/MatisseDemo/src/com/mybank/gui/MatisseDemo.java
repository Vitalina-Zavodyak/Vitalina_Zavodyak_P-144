    private void loadData() {
    try (Scanner scanner = new Scanner(new File("test.dat"))) {
        scanner.useLocale(Locale.US);

        int numberOfCustomers = scanner.nextInt();

        for (int i = 0; i < numberOfCustomers; i++) {
            String firstName = scanner.next();
            String lastName = scanner.next();
            int numberOfAccounts = scanner.nextInt();

            Bank.addCustomer(firstName, lastName);
            Customer customer = Bank.getCustomer(i);

            for (int j = 0; j < numberOfAccounts; j++) {
                String type = scanner.next();
                double balance = scanner.nextDouble();
                double extra = scanner.nextDouble();

                if (type.equalsIgnoreCase("C")) {
                    customer.addAccount(
                            new CheckingAccount(balance, extra));
                } else if (type.equalsIgnoreCase("S")) {
                    customer.addAccount(
                            new SavingsAccount(balance, extra));
                }
            }
        }

        clientsComboBox.removeAllItems();

        for (int i = 0; i < numberOfCustomers; i++) {
            Customer customer = Bank.getCustomer(i);
            clientsComboBox.addItem(
                    customer.getLastName() + ", "
                    + customer.getFirstName());
        }

    } catch (FileNotFoundException ex) {
        JOptionPane.showMessageDialog(this,
                "File test.dat not found!");
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this,
                "Error reading test.dat: " + ex.getMessage());
    }
}
    private void showButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_showButtonActionPerformed


    int index = clientsComboBox.getSelectedIndex();

    if (index < 0) {
        return;
    }

    Customer customer = Bank.getCustomer(index);

    StringBuilder text = new StringBuilder();

    text.append("Customer: ")
            .append(customer.getFirstName()).append(" ")
            .append(customer.getLastName()).append("\n\n");

    for (int i = 0; i < customer.getNumberOfAccounts(); i++) {

        Account account = customer.getAccount(i);

        String type;

        if (account instanceof CheckingAccount) {
            type = "Checking Account";
        } else {
            type = "Savings Account";
        }

        text.append(type).append("\n");

        text.append("Balance: ")
                .append(String.format(Locale.US, "%.2f",
                        account.getBalance()))
                .append("\n\n");
    }

    outputTextArea.setText(text.toString());
    statusLabel.setText("Customer information displayed");
    }//GEN-LAST:event_showButtonActionPerformed

    private void reportButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_reportButtonActionPerformed
        // TODO add your handling code here:

    StringBuilder report = new StringBuilder();
    double totalBalance = 0;

    report.append("MYBANK CLIENTS REPORT\n");
    report.append("====================\n\n");

    for (int i = 0; i < Bank.getNumberOfCustomers(); i++) {

        Customer customer = Bank.getCustomer(i);

        report.append(customer.getFirstName()).append(" ")
                .append(customer.getLastName()).append("\n");

        for (int j = 0; j < customer.getNumberOfAccounts(); j++) {

            Account account = customer.getAccount(j);

            totalBalance += account.getBalance();

            String type;

            if (account instanceof CheckingAccount) {
                type = "Checking Account";
            } else {
                type = "Savings Account";
            }

            report.append("  ")
                    .append(type)
                    .append(": ")
                    .append(String.format(Locale.US, "%.2f",
                            account.getBalance()))
                    .append("\n");
        }

        report.append("\n");
    }

    report.append("--------------------\n");
    report.append("Total balance: ")
            .append(String.format(Locale.US, "%.2f", totalBalance));

    outputTextArea.setText(report.toString());
    statusLabel.setText("Full customer report displayed");
    }//GEN-LAST:event_reportButtonActionPerformed
        
